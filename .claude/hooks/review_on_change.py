#!/usr/bin/env python3
"""PostToolUse hook: after a source file changes, ask Claude to run the `code-reviewer` subagent on it.

Hooks cannot launch subagents themselves, so this script returns `decision: "block"` with a reason; on
PostToolUse that does not undo the edit — the reason is fed back to Claude, which then delegates the
review to `.claude/agents/code-reviewer.md`.

Guards:
- only reviewable source/config files inside the project (no docs, data, lockfiles, build output);
- never sensitive files (.env*, keys) — their contents must not be sent to a reviewer;
- skips a file whose content hash was already reviewed this session (no-op saves);
- caps reviews per file per session so fix → review → fix cannot loop forever.
Any unexpected error exits 0 silently: a broken hook must never block editing.
"""
import hashlib
import json
import os
import re
import sys
import tempfile

MAX_REVIEWS_PER_FILE = 3

REVIEWABLE_EXTENSIONS = {
    ".py", ".js", ".jsx", ".ts", ".tsx", ".css", ".html", ".sh",
    ".yml", ".yaml", ".conf", ".ini", ".toml", ".sql",
}
REVIEWABLE_NAMES = {"Dockerfile", "requirements.txt", "package.json", "entrypoint.sh"}
SKIP_DIRS = {
    "node_modules", "dist", "build", "__pycache__", ".pytest_cache", ".git", ".claude",
    ".data", "uploads", "versions",  # versions = autogenerated Alembic migrations
}
SENSITIVE = re.compile(r"(^\.env($|\.)|\.pem$|\.key$|id_rsa|secret|credential)", re.IGNORECASE)


def should_review(rel_path: str) -> bool:
    parts = rel_path.split(os.sep)
    name = parts[-1]
    if SENSITIVE.search(name) or any(p in SKIP_DIRS for p in parts[:-1]):
        return False
    if name == "package-lock.json" or name.endswith(".lock"):
        return False
    return name in REVIEWABLE_NAMES or os.path.splitext(name)[1].lower() in REVIEWABLE_EXTENSIONS


def load_state(path: str) -> dict:
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return {}


def main() -> None:
    payload = json.load(sys.stdin)
    tool_input = payload.get("tool_input") or {}
    tool_response = payload.get("tool_response") or {}
    file_path = tool_input.get("file_path") or tool_input.get("notebook_path") or tool_response.get("filePath")
    if not file_path:
        return

    project_dir = os.path.realpath(os.environ.get("CLAUDE_PROJECT_DIR") or payload.get("cwd") or os.getcwd())
    abs_path = os.path.realpath(file_path if os.path.isabs(file_path) else os.path.join(project_dir, file_path))
    if os.path.commonpath([abs_path, project_dir]) != project_dir or not os.path.isfile(abs_path):
        return  # outside this repo, or deleted
    rel_path = os.path.relpath(abs_path, project_dir)
    if not should_review(rel_path):
        return

    with open(abs_path, "rb") as f:
        digest = hashlib.sha256(f.read()).hexdigest()

    session = re.sub(r"[^A-Za-z0-9_-]", "", str(payload.get("session_id") or "nosession"))[:64]
    state_path = os.path.join(tempfile.gettempdir(), f"claude-code-review-{session}.json")
    state = load_state(state_path)
    entry = state.get(rel_path, {"hash": None, "count": 0})

    if entry["hash"] == digest:
        return  # this exact content was already queued for review
    if entry["count"] >= MAX_REVIEWS_PER_FILE:
        print(json.dumps({"systemMessage": f"Code review skipped for {rel_path}: "
                          f"{MAX_REVIEWS_PER_FILE}-review cap reached this session."}))
        return

    state[rel_path] = {"hash": digest, "count": entry["count"] + 1}
    with open(state_path, "w", encoding="utf-8") as f:
        json.dump(state, f)

    reason = (
        f"Code-review hook: `{rel_path}` was changed (review {entry['count'] + 1}/{MAX_REVIEWS_PER_FILE} "
        "for this file this session). Delegate a review to the project's `code-reviewer` subagent "
        "(Agent tool, subagent_type: \"code-reviewer\"). In the prompt give the file path(s) and a one-line "
        "summary of what you changed and why — never paste secret values (e.g. from .env). If you are in "
        "the middle of a set of related edits, finish them first and send all changed files in ONE review "
        "request. Then fix BLOCKER/MAJOR findings (or explain why a finding is wrong) before reporting the "
        "task as done, and mention the review verdict in your summary."
    )
    print(json.dumps({
        "decision": "block",
        "reason": reason,
        "systemMessage": f"Code review requested for {rel_path}",
    }))


if __name__ == "__main__":
    try:
        main()
    except Exception:  # noqa: BLE001 — a failing hook must never interfere with editing
        sys.exit(0)
